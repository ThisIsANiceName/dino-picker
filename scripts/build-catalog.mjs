// Regenerates src/data/catalog/dinos.js and bodyTypeHints.js from the JSON sources.
// Usage: node scripts/build-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'catalog')
const banner = '// GENERATED by scripts/build-catalog.mjs from the matching .json file. Do not edit by hand.\n'

for (const name of ['dinos', 'bodyTypeHints']) {
  const json = JSON.parse(readFileSync(join(dir, `${name}.json`), 'utf8'))
  writeFileSync(join(dir, `${name}.js`), `${banner}export default ${JSON.stringify(json, null, 2)}\n`)
  console.log(`wrote ${name}.js`)
}
